/**
 * Generates supabase/seed.sql from the demo content in src/lib/demo.
 *   npm run db:seed-sql
 * Lead timestamps are written relative to now() so the CRM looks current whenever the seed is applied.
 * Every seeded row has is_demo = true; delete them with:
 *   delete from leads where is_demo; delete from properties where is_demo; delete from agents where is_demo;
 */
import { demoProperties } from "../src/lib/demo/properties";
import { demoAgents } from "../src/lib/demo/people";
import { generateDemoLeads } from "../src/lib/demo/leads";

const now = new Date();
const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replace(/'/g, "''")}'`);
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const ago = (iso: string) => `now() - interval '${Math.max(0, Math.round((now.getTime() - new Date(iso).getTime()) / 1000))} seconds'`;
const at = (iso: string | null) => {
  if (!iso) return "null";
  const diff = Math.round((new Date(iso).getTime() - now.getTime()) / 1000);
  return diff >= 0 ? `now() + interval '${diff} seconds'` : `now() - interval '${-diff} seconds'`;
};

const out: string[] = ["-- Generated by scripts/generate-seed-sql.ts — demonstration data only (is_demo = true).", "begin;", ""];

for (const a of demoAgents) {
  out.push(
    `insert into public.agents (id, name, title, email, phone, languages, focus, active, is_demo) values (${q(a.id)}, ${q(a.name)}, ${q(a.title)}, ${q(a.email)}, ${q(a.phone)}, ${arr(a.languages)}, ${q(a.focus)}, ${a.active}, true) on conflict (id) do nothing;`,
  );
}
out.push("");

for (const p of demoProperties) {
  out.push(
    `insert into public.properties (id, ref, slug, title, category, segment, type, community_slug, building, price, bedrooms, bathrooms, area_sqft, plot_sqft, furnishing, summary, description, amenities, images, floor_plan, lat, lng, location_precision, agent_id, featured, published, status, verification, off_plan, rental_yield, is_demo, created_at, updated_at) values (` +
      [
        q(p.id),
        q(p.ref),
        q(p.slug),
        q(p.title),
        q(p.category),
        q(p.segment),
        q(p.type),
        q(p.communitySlug),
        q(p.building),
        p.price,
        p.bedrooms,
        p.bathrooms,
        p.areaSqft,
        p.plotSqft ?? "null",
        q(p.furnishing),
        q(p.summary),
        arr(p.description),
        arr(p.amenities),
        j(p.images),
        j(p.floorPlan),
        p.location.lat,
        p.location.lng,
        q(p.location.precision),
        q(p.agentId),
        p.featured,
        p.published,
        q(p.status),
        j(p.verification),
        j(p.offPlan),
        j(p.rentalYield),
        "true",
        q(p.createdAt),
        q(p.updatedAt),
      ].join(", ") +
      ") on conflict (id) do nothing;",
  );
}
out.push("");

for (const l of generateDemoLeads(now)) {
  out.push(
    `insert into public.leads (id, created_at, updated_at, name, email, phone, intent, budget_band, preferred_community, contact_method, message, source, property_id, viewing, sell_details, status, agent_id, follow_up_at, utm, consent, is_demo) values (` +
      [
        q(l.id),
        ago(l.createdAt),
        ago(l.updatedAt),
        q(l.name),
        q(l.email),
        q(l.phone),
        q(l.intent),
        q(l.budgetBand),
        q(l.preferredCommunity),
        q(l.contactMethod),
        q(l.message),
        q(l.source),
        q(l.propertyId),
        j(l.viewing),
        j(l.sellDetails),
        q(l.status),
        q(l.agentId),
        at(l.followUpAt),
        j(l.utm),
        j(l.consent),
        "true",
      ].join(", ") +
      ") on conflict (id) do nothing;",
  );
  for (const n of l.notes) {
    out.push(
      `insert into public.lead_notes (lead_id, author_id, author_name, channel, body, created_at) values (${q(l.id)}, ${q(n.authorId)}, ${q(n.authorName)}, ${q(n.channel)}, ${q(n.body)}, ${ago(n.createdAt)});`,
    );
  }
  for (const a of l.activity) {
    out.push(
      `insert into public.lead_activity (lead_id, type, actor_name, description, at) values (${q(l.id)}, ${q(a.type)}, ${q(a.actorName)}, ${q(a.description)}, ${ago(a.at)});`,
    );
  }
}

out.push("", "commit;", "");
process.stdout.write(out.join("\n"));

const img = (p: Photo, kind: PropertyImage["kind"] = "photo"): PropertyImage => ({ src: p.src, alt: p.alt, credit: p.credit, kind });

type Seed = Omit<
  Property,
  | "id"
  | "slug"
  | "isDemo"
  | "published"
  | "status"
  | "verification"
  | "rentalYield"
  | "location"
  | "floorPlan"
  | "updatedAt"
  | "plotSqft"
  | "furnishing"
  | "building"
  | "offPlan"
  | "agentId"
  | "featured"
> &
  Partial<Pick<Property, "plotSqft" | "furnishing" | "building" | "offPlan" | "agentId" | "featured" | "status">>;

function listing(seed: Seed): Property {
  const community = communities.find((c) => c.slug === seed.communitySlug);
  if (!community) throw new Error(`Unknown community ${seed.communitySlug}`);
  return {
    plotSqft: null,
    furnishing: null,
    building: null,
    offPlan: null,
    agentId: null,
    featured: false,
    status: "available",
    ...seed,
    id: `prop_${seed.ref.toLowerCase().replace(/[^a-z0-9]/g, "")}`,
    slug: `${slugify(seed.title)}-${seed.ref.toLowerCase()}`,
    location: { ...community.location, precision: "community" },
    floorPlan: null,
    verification: null,
    rentalYield: null,
    published: true,
    isDemo: true,
    updatedAt: seed.createdAt,
  };
}

